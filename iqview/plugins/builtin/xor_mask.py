"""iqview/plugins/builtin/xor_mask.py

Built-in IQView Plugin: XOR Mask (De-whitening / Scrambling).

XORs `metadata["bits"]` with an input mask given in hex.
The mask pattern is repeated periodically and truncated to match the exact length of the data.
Includes built-in presets for common RF de-whitening standards (CC1101 PN9, CC2500, alternating, invert).
"""

from __future__ import annotations

import copy
import re
from typing import Any, Dict, List, Optional
import numpy as np

from iqview import PluginResult, PluginContext
from iqview.overlays import OverlayShape


PLUGIN_NAME              = "XOR Mask"
PLUGIN_DESCRIPTION       = (
    "XORs metadata['bits'] with a periodic hex mask or standard de-whitening sequence "
    "(CC1101 PN9, CC2500, Alternating, Invert), repeating and truncating to packet length."
)
PLUGIN_CATEGORY          = "Bit Manipulation"
PLUGIN_NEEDS_WIDEBAND_IQ = False

PLUGIN_DOC = """# XOR Mask (De-whitener)

Applies a bitwise XOR mask to `metadata["bits"]`. The mask is repeated periodically and truncated to the length of the data stream. Commonly used for data de-whitening, descrambling, and bit inversion.

### Presets
* **Custom Hex Mask**: Uses the user-defined `mask_hex` string (e.g. `0xAA`, `0x12345678`).
* **Invert All (0xFF)**: Flips every bit ($b_i \\oplus 1$).
* **Alternating (0xAA)**: Flips every second bit (`10101010`).
* **Alternating (0x55)**: `01010101`.
* **CC1101 PN9 / TI CC2500**: Standard 511-byte pseudo-random sequence generated by $x^9 + x^5 + 1$ with seed `0x1FF`.

### Parameters
* **Preset** (`preset`): Preset selection or `"Custom Hex Mask"`.
* **Mask (Hex)** (`mask_hex`): Custom hex mask string (e.g. `0xAA`, `0xD391`).
* **Byte Bit Order** (`bit_order`): `"msb_first"` (default) or `"lsb_first"` when unpacking mask bytes.

### Output Metadata
* `metadata["bits_pre_xor"]`: Bits before XOR mask
* `metadata["bits"]`: De-whitened / XORed bitstream
* `metadata["hex"]`: Hex formatted output
* `metadata["xor_mask_applied"]`: Hex representation of the mask applied
"""

